skewed_df = generate_dataset(
    spark,
    num_records=10000,
    num_keys=10,
    distribution="skewed",
    skew_level=0.8,
    num_partitions=2
)

skewed_df.groupBy("key") \
    .count() \
    .orderBy(F.desc("count")) \
    .show()

"""Visualization"""

import matplotlib.pyplot as plt

def plot_key_distribution(df, title):
    counts = (
        df.groupBy("key")
          .count()
          .orderBy("key")
          .collect()
    )

    keys = [row["key"] for row in counts]
    frequencies = [row["count"] for row in counts]

    plt.figure(figsize=(10, 4))
    plt.bar(keys, frequencies)

    plt.xlabel("Key")
    plt.ylabel("Frequency")
    plt.title(title)
    plt.xticks(rotation=45)
    plt.tight_layout()
    plt.show()


plot_key_distribution(
    uniform_df,
    "Uniform Key Distribution"
)

plot_key_distribution(
    skewed_df,
    "Skewed Key Distribution (80% Hot Key)"
)

